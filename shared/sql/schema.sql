    CONSTRAINT fk_candidate_languages_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT uq_candidate_languages_candidate_language
        UNIQUE (candidate_id, language)
);

-- 9. Candidate Links
CREATE TABLE candidate_links (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    link_type VARCHAR(50) NOT NULL,
    url TEXT NOT NULL,
    label VARCHAR(255),

    CONSTRAINT fk_candidate_links_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT uq_candidate_links_candidate_url
        UNIQUE (candidate_id, url)
);

