-- =============================================
-- 7. UPLOADED FILES & PROCESSING JOBS
-- =============================================

-- 15. Uploaded Files
CREATE TABLE uploaded_files (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    source_type source_type NOT NULL,
    original_filename VARCHAR(500) NOT NULL,
    file_size BIGINT NOT NULL,
    file_hash VARCHAR(128) NOT NULL UNIQUE,
    storage_location TEXT NOT NULL,
    mime_type VARCHAR(150),
    uploaded_at TIMESTAMP NOT NULL,
    validated_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_uploaded_files_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id)
);

CREATE INDEX idx_uploaded_files_candidate_source
    ON uploaded_files(candidate_id, source_type);


-- 16. Processing Jobs
CREATE TABLE processing_jobs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id INTEGER NOT NULL UNIQUE,
    status processing_status NOT NULL DEFAULT 'queued',
    attempt_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    next_retry_at TIMESTAMP,
    failure_reason TEXT,
    changed_field_count INTEGER,
    pending_review_count INTEGER,
    extracted_at TIMESTAMP,
    model_name VARCHAR(255),
    model_version VARCHAR(100),
    prompt_version VARCHAR(100),
    document_language VARCHAR(20),
    extraction_warnings TEXT,

    CONSTRAINT fk_processing_jobs_file
        FOREIGN KEY (file_id)
        REFERENCES uploaded_files(id)
);

-- =============================================
-- 8. UNKNOWN SKILLS
-- =============================================

CREATE TABLE unknown_skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    skill_name VARCHAR(500) NOT NULL,
    source_file_id INTEGER NOT NULL,
    confidence FLOAT,
    evidence TEXT NOT NULL,
    status unknown_skill_status NOT NULL DEFAULT 'pending',
    resolved_skill_id INTEGER,
    created_at TIMESTAMP NOT NULL,
    resolved_at TIMESTAMP,

    CONSTRAINT fk_unknown_skills_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT fk_unknown_skills_source_file
        FOREIGN KEY (source_file_id)
        REFERENCES uploaded_files(id),

    CONSTRAINT fk_unknown_skills_resolved_skill
        FOREIGN KEY (resolved_skill_id)
        REFERENCES skills(id),

    CONSTRAINT chk_unknown_skills_confidence
        CHECK (confidence >= 0 AND confidence <= 1)
);

-- =============================================
-- 9. DATA PROVENANCE
-- =============================================

-- 18. Data Provenance
CREATE TABLE data_provenance (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    item_type provenance_item_type NOT NULL,
    item_id VARCHAR(255) NOT NULL,
    field_name VARCHAR(150) NOT NULL,
    resolution_method provenance_resolution_method NOT NULL,
    approved_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_data_provenance_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT uq_data_provenance_item_field
        UNIQUE (item_type, item_id, field_name)
);

CREATE INDEX idx_data_provenance_candidate
    ON data_provenance(candidate_id);


-- 19. Data Provenance Sources
CREATE TABLE data_provenance_sources (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provenance_id INTEGER NOT NULL,
    job_id INTEGER NOT NULL,
    source_value JSONB NOT NULL,
    confidence FLOAT,
    evidence TEXT NOT NULL,

    CONSTRAINT fk_provenance_sources_provenance
        FOREIGN KEY (provenance_id)
        REFERENCES data_provenance(id),

    CONSTRAINT fk_provenance_sources_job
        FOREIGN KEY (job_id)
        REFERENCES processing_jobs(id),

    CONSTRAINT uq_provenance_sources_provenance_job
        UNIQUE (provenance_id, job_id),

    CONSTRAINT chk_provenance_sources_confidence
        CHECK (confidence >= 0 AND confidence <= 1)
);

-- =============================================
-- 10. CONFLICTS & CONFLICT OPTIONS
-- =============================================

-- 20. Conflicts
CREATE TABLE conflicts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    field_name VARCHAR(150) NOT NULL,
    item_type VARCHAR(100) NOT NULL,
    item_id VARCHAR(255) NOT NULL,
    status conflict_status NOT NULL DEFAULT 'pending',
    resolution_method conflict_resolution_method,
    applied_rule VARCHAR(500),
    source_count INTEGER,
    resolved_value JSONB,
    resolved_at TIMESTAMP,

    CONSTRAINT fk_conflicts_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id)
);


-- 21. Conflict Options
CREATE TABLE conflict_options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conflict_id INTEGER NOT NULL,
    value JSONB NOT NULL,
    source_file_id INTEGER,
    confidence FLOAT,
    evidence TEXT,

    CONSTRAINT fk_conflict_options_conflict
        FOREIGN KEY (conflict_id)
        REFERENCES conflicts(id),

    CONSTRAINT fk_conflict_options_source_file
        FOREIGN KEY (source_file_id)
        REFERENCES uploaded_files(id),

    CONSTRAINT chk_conflict_options_confidence
        CHECK (confidence >= 0 AND confidence <= 1)
);

-- =============================================
-- 11. HUMAN REVIEWS & HUMAN AUDIT LOG
-- =============================================

-- 22. Human Reviews
CREATE TABLE human_reviews (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    review_target_type review_target_type NOT NULL,
    item_id INTEGER NOT NULL,
    review_reason review_reason NOT NULL,
    review_status review_status NOT NULL DEFAULT 'pending',
    admin_id INTEGER,
    reviewed_at TIMESTAMP,
    review_result TEXT,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_human_reviews_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT fk_human_reviews_admin
        FOREIGN KEY (admin_id)
        REFERENCES admins(id)
);


-- 23. Human Audit Log
CREATE TABLE human_audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    item_type provenance_item_type NOT NULL,
    item_id VARCHAR(255) NOT NULL,
    field_name VARCHAR(150) NOT NULL,
    previous_value JSONB,
    new_value JSONB,
    changed_by INTEGER NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    reason TEXT,

    CONSTRAINT fk_human_audit_log_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT fk_human_audit_log_admin
        FOREIGN KEY (changed_by)
        REFERENCES admins(id)
);
-- Indexes for review queue and joins
CREATE INDEX idx_unknown_skills_candidate ON unknown_skills(candidate_id);
CREATE INDEX idx_unknown_skills_status ON unknown_skills(status);
CREATE INDEX idx_candidate_skills_skill ON candidate_skills(skill_id);
CREATE INDEX idx_provenance_sources_job ON data_provenance_sources(job_id);
CREATE INDEX idx_conflicts_candidate ON conflicts(candidate_id);
CREATE INDEX idx_conflicts_status ON conflicts(status);
CREATE INDEX idx_conflicts_item ON conflicts(item_type, item_id);
CREATE INDEX idx_conflict_options_conflict ON conflict_options(conflict_id);
CREATE INDEX idx_human_reviews_candidate ON human_reviews(candidate_id);
CREATE INDEX idx_human_reviews_status ON human_reviews(review_status);
CREATE INDEX idx_human_reviews_target ON human_reviews(review_target_type, item_id);
CREATE INDEX idx_human_audit_log_candidate ON human_audit_log(candidate_id);
CREATE INDEX idx_human_audit_log_item ON human_audit_log(item_type, item_id, field_name);
CREATE INDEX idx_processing_jobs_status ON processing_jobs(status, next_retry_at);

-- Extra integrity checks
ALTER TABLE candidate_skills
    ADD CONSTRAINT chk_candidate_skills_months CHECK (months_of_experience IS NULL OR months_of_experience >= 0);

