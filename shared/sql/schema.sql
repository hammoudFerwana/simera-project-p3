
-- =============================================
-- 1. ENUM TYPES
-- =============================================

CREATE TYPE unknown_skill_status AS ENUM (
    'pending',
    'accepted',
    'rejected'
);

CREATE TYPE language_proficiency AS ENUM (
    'basic',
    'intermediate',
    'advanced',
    'native'
);

CREATE TYPE source_type AS ENUM (
    'cv',
    'linkedin',
    'simera_profile'
);

CREATE TYPE processing_status AS ENUM (
    'queued',
    'processing',
    'completed',
    'failed',
    'completed_with_review'
);

CREATE TYPE provenance_item_type AS ENUM (
    'candidate_profile',
    'work_experience',
    'education',
    'candidate_skills',
    'candidate_languages',
    'candidate_links',
    'certifications',
    'projects',
    'awards',
    'publications',
    'volunteering'
);

CREATE TYPE provenance_resolution_method AS ENUM (
    'source_agreement',
    'majority',
    'human_review',
    'vetted'
);

CREATE TYPE conflict_status AS ENUM (
    'pending',
    'resolved'
);

CREATE TYPE conflict_resolution_method AS ENUM (
    'automatic_rule',
    'human_review'
);

CREATE TYPE review_target_type AS ENUM (
    'conflict',
    'unknown_skill'
);

CREATE TYPE review_reason AS ENUM (
    'conflict',
    'intra_source_conflict',
    'low_confidence',
    'validation_failure',
    'item_match_uncertain',
    'unknown_skill'
);

CREATE TYPE review_status AS ENUM (
    'pending',
    'in_review',
    'completed'
);

-- =============================================
-- 2. USERS & CANDIDATE PROFILE
-- =============================================

-- 1. Users
CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    otp_hash VARCHAR(255),
    otp_expires_at TIMESTAMP,
    otp_attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP
);

-- 2. Admins
CREATE TABLE admins (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE,

    CONSTRAINT fk_admins_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
);

-- 3. Candidate Profiles
CREATE TABLE candidate_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL UNIQUE,
    first_name VARCHAR(250),
    last_name VARCHAR(250),
    headline VARCHAR(500),
    summary TEXT,
    phone VARCHAR(30),
    industry VARCHAR(500),
    profession VARCHAR(500),
    city VARCHAR(250),
    country_code VARCHAR(2),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,

    CONSTRAINT fk_candidate_profiles_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
);

-- 4. Skills
CREATE TABLE skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    canonical_name VARCHAR(500) NOT NULL UNIQUE,
    created_at TIMESTAMP NOT NULL
);

-- =============================================
-- 3. EDUCATION & WORK EXPERIENCE
-- =============================================

-- 5. Education
CREATE TABLE education (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    institution_name VARCHAR(500) NOT NULL,
    degree_level VARCHAR(500),
    degree_name VARCHAR(500),
    field_of_study VARCHAR(500),
    start_date VARCHAR(20),
    end_date VARCHAR(20),
    is_current BOOLEAN,
    gpa VARCHAR(50),
    honors TEXT,
    location VARCHAR(500),
    description TEXT,
    deduplication_key VARCHAR(128) NOT NULL,

    CONSTRAINT fk_education_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT uq_education_candidate_dedup
        UNIQUE (candidate_id, deduplication_key)
);

-- 6. Work Experience
CREATE TABLE work_experience (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    job_title VARCHAR(500) NOT NULL,
    company_name VARCHAR(500) NOT NULL,
    start_date VARCHAR(20),
    end_date VARCHAR(20),
    is_current BOOLEAN,
    location VARCHAR(500),
    employment_type VARCHAR(250),
    work_mode VARCHAR(250),
    description TEXT,
    responsibilities TEXT,
    achievements TEXT,
    skills_used TEXT,
    company_url TEXT,
    deduplication_key VARCHAR(128) NOT NULL,

    CONSTRAINT fk_work_experience_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT uq_work_experience_candidate_dedup
        UNIQUE (candidate_id, deduplication_key)
);

-- =============================================
-- 4. CANDIDATE SKILLS & UNKNOWN SKILLS
-- =============================================

-- 7. Candidate Skills
CREATE TABLE candidate_skills (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
    skill_id INTEGER NOT NULL,
    proficiency_level VARCHAR(100),
    months_of_experience INTEGER,
    created_at TIMESTAMP NOT NULL,

    CONSTRAINT fk_candidate_skills_candidate
        FOREIGN KEY (candidate_id)
        REFERENCES candidate_profiles(id),

    CONSTRAINT fk_candidate_skills_skill
        FOREIGN KEY (skill_id)
        REFERENCES skills(id),

    CONSTRAINT uq_candidate_skills_candidate_skill
        UNIQUE (candidate_id, skill_id)
);


-- =============================================
-- 5. CANDIDATE LANGUAGES & LINKS
-- =============================================

-- 8. Candidate Languages
CREATE TABLE candidate_languages (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidate_id INTEGER NOT NULL,
